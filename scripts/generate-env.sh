#!/usr/bin/env bash
set -euo pipefail

ENV_FILE="${1:-.env}"

# ─── Cipher pool ─────────────────────────────────────────────────────────────
# Strong OpenSSL suites that Node.js / OpenSSL supports.
# Shuffling this list changes the TLS ClientHello order → different JA3/JA4.
CIPHERS=(
  "ECDHE-ECDSA-AES128-GCM-SHA256"
  "ECDHE-RSA-AES128-GCM-SHA256"
  "ECDHE-ECDSA-AES256-GCM-SHA384"
  "ECDHE-RSA-AES256-GCM-SHA384"
  "ECDHE-ECDSA-CHACHA20-POLY1305"
  "ECDHE-RSA-CHACHA20-POLY1305"
  "DHE-RSA-AES128-GCM-SHA256"
  "DHE-RSA-AES256-GCM-SHA384"
  "ECDHE-ECDSA-AES128-SHA256"
  "ECDHE-RSA-AES128-SHA256"
)

# Shuffle using mapfile to avoid word-splitting issues
mapfile -t SHUFFLED_CIPHERS < <(printf "%s\n" "${CIPHERS[@]}" | shuf)

# Pick a random subset of 6–9 ciphers
COUNT=$((6 + RANDOM % 4))
SELECTED_CIPHERS="${SHUFFLED_CIPHERS[0]}"
for ((i = 1; i < COUNT; i++)); do
  SELECTED_CIPHERS="${SELECTED_CIPHERS}:${SHUFFLED_CIPHERS[i]}"
done

# ─── User-Agent pool ──────────────────────────────────────────────────────────
# Real Node.js HTTP library signatures — no browser emulation.
USER_AGENTS=(
  "axios/1.7.9 (Node.js/v20.18.0; linux-x64)"
  "axios/1.7.7 (Node.js/v20.17.0; linux-x64)"
  "node-fetch/3.3.2 (+https://github.com/node-fetch/node-fetch; Node.js/v20.18.0)"
  "node-fetch/2.6.12 (Node.js/v20.18.0; linux-x64)"
  "undici/6.21.1 (Node.js/v20.18.0; linux-x64)"
  "undici/5.28.4 (Node.js/v20.16.0; linux-x64)"
  "got/14.4.2 (https://github.com/sindresorhus/got; Node.js/v20.18.0)"
  "Node.js/v20.18.0 (linux; x64)"
  "Node.js/v20.17.0 (linux; x64)"
)

SELECTED_UA="${USER_AGENTS[$((RANDOM % ${#USER_AGENTS[@]}))]}"

# ─── Machine ID ───────────────────────────────────────────────────────────────
MACHINE_ID=$(openssl rand -hex 16)

# ─── Write .env ───────────────────────────────────────────────────────────────
cat > "$ENV_FILE" <<EOF
# Auto-generated by scripts/generate-env.sh — do not edit manually.
# Re-run ./reinstall.sh to rotate all values.

# WARP SOCKS5 proxy (shared network namespace with warp-proxy container)
HTTP_PROXY=http://127.0.0.1:9091
HTTPS_PROXY=http://127.0.0.1:9091
ALL_PROXY=http://127.0.0.1:9091

# Node.js TLS Anti-Fingerprint
# NODE_OPTIONS is read by the node binary at process start (runtime, not compile-time).
# Permuting the cipher list changes the TLS ClientHello → different JA3/JA4 hash.
NODE_OPTIONS=--tls-cipher-list=${SELECTED_CIPHERS}

# Node.js Client Identity (authentic library UA — no browser emulation)
USER_AGENT=${SELECTED_UA}

# Unique session identifier (rotated on every reinstall)
MACHINE_ID=${MACHINE_ID}
EOF

echo "[env] Generated fresh stealth profile → ${ENV_FILE}"
echo "      Ciphers (${COUNT}): ${SELECTED_CIPHERS}"
echo "      User-Agent:        ${SELECTED_UA}"
